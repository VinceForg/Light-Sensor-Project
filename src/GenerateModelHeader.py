"""Part 3 -- generate model.h for the ESP32.

Reads surfaces.npz (per-cluster peak-normalised maps on the GRID_N x GRID_N
grid) and the training scaling bounds, and writes model.h with:
    GRID_N, NUM_CLASSES, CLASS_TABLE (uint8, PROGMEM), SCALE_BOUNDS,
    CLASS_NAMES, REJECT_TAU

Preprocessing the firmware MUST reproduce, in this order:
    x = analogRead(pin) / 4095.0      (same as data logging)
    x = EMA(x), alpha = EMA_ALPHA     (same as FilterCSV.py)
    x = log1pf(x * 4095.0)            (same as PipelineCommon.load_dataset)
    x = (x - min) / (max - min)       (SCALE_BOUNDS, from training data)
"""
import numpy as np
from pathlib import Path
from PipelineCommon import (load_split_scaled, quantize,
                            GRID_N, REJECT_TAU)

# DBSCAN cluster id -> name. Fill this in from the "majority label per
# cluster" lines of ClusterDBScan.py. Several clusters may share a name.
CLUSTER_NAMES = {
    0: "shade",
    1: "sun",
    2: "indoor",   # incandescent + LED merged by DBSCAN
    3: "shade",
}

EMA_ALPHA = 0.2                 # must match FilterCSV.py
SURFACES = "../figures/generated/surfaces.npz"
OUT = Path("../figures/generated/model.h")

surfaces = np.load(SURFACES)
classes = sorted(int(k[1:]) for k in surfaces.files)
K = len(classes)

missing = [c for c in classes if c not in CLUSTER_NAMES]
if missing:
    raise SystemExit(f"No name for cluster(s) {missing}: update CLUSTER_NAMES "
                     f"from ClusterDBScan.py output.")

tables = [quantize(surfaces[f"c{c}"]) for c in classes]   # each (GRID_N, GRID_N), [row][col]
for c, t in zip(classes, tables):
    assert t.shape == (GRID_N, GRID_N), f"cluster {c}: shape {t.shape}"

lo, hi = load_split_scaled()["bounds"]                     # training bounds, log units
bounds = [lo[0], hi[0], lo[1], hi[1]]                      # xmin, xmax, ymin, ymax

lines = [
    "// model.h -- generated by GenerateModelHeader.py. Do not edit by hand.",
    "//",
    "// Firmware preprocessing, in this order:",
    "//   x = analogRead(pin) / 4095.0f",
    f"//   x = EMA(x) with alpha = {EMA_ALPHA}",
    "//   x = log1pf(x * 4095.0f)",
    "//   x = (x - SCALE_BOUNDS[min]) / (SCALE_BOUNDS[max] - SCALE_BOUNDS[min])",
    "// Grid index: col from scaled UV (x), row from scaled IR (y), clipped to [0, GRID_N-1].",
    "#pragma once",
    "#include <Arduino.h>",
    "",
    f"#define GRID_N {GRID_N}",
    f"#define NUM_CLASSES {K}",
    f"#define REJECT_TAU {REJECT_TAU}f",
    f"#define EMA_ALPHA {EMA_ALPHA}f",
    "",
    "// CLASS_TABLE[class][row][col], byte = round(255 * normalised density)",
    "const uint8_t CLASS_TABLE[NUM_CLASSES][GRID_N][GRID_N] PROGMEM = {",
]
for i, (c, t) in enumerate(zip(classes, tables)):
    lines.append(f"  {{ // class {i}: cluster {c} -> {CLUSTER_NAMES[c]}")
    for r in range(GRID_N):
        row = ", ".join(f"{v:3d}" for v in t[r])
        lines.append(f"    {{{row}}}{',' if r < GRID_N - 1 else ''}")
    lines.append(f"  }}{',' if i < K - 1 else ''}")
lines += [
    "};",
    "",
    "// xmin, xmax, ymin, ymax -- training bounds in log1p(ADC counts) units",
    "const float SCALE_BOUNDS[4] = {" + ", ".join(f"{b:.6f}f" for b in bounds) + "};",
    "",
    "const char* CLASS_NAMES[NUM_CLASSES] = {"
    + ", ".join(f'"{CLUSTER_NAMES[c]}"' for c in classes) + "};",
    "",
]

OUT.write_text("\n".join(lines), encoding="utf-8")

table_bytes = K * GRID_N * GRID_N
print(f"wrote {OUT.name}: K={K}, G={GRID_N}")
print(f"table size  K*G^2 = {K}*{GRID_N}^2 = {table_bytes} bytes")
print(f"bounds      4 floats = 16 bytes  -> total {table_bytes + 16} bytes")
print("class names:", [CLUSTER_NAMES[c] for c in classes])
print("SCALE_BOUNDS:", [round(float(b), 4) for b in bounds])
